//! Exponent-indexed window of `1/pi`, for `reduce_pi_wide`.
//!
//! Entry `e` (the raw f32 biased exponent, 0..=255) holds a slice of
//! `beta(e) = (2^(e-150) / pi) mod 2` at **fixed bit positions**, not the
//! shipped-until-2026-08 significant-bit `f64` split: four `u32` chunks of
//! **27 bits each**, chunk `i` holding bits `2^-(1+27i)` down to
//! `2^-(27+27i)` of `beta` (truncated, so the four sum to a value below the
//! true `beta` with no cancellation between them). Together they name
//! `beta`'s low ~108 fraction bits absolutely.
//!
//! Fixed positions are what keeps the SIMD vectorization factor at 8: the
//! earlier `[f64; 256]` tables made LLVM drop every vector loop containing
//! one of their gathers from `zmm` to `ymm` (see graveyard.md, "the gather:
//! 3.2x throughput"), while a `vpgatherdd` table does not. The price is the
//! `|x| < 2^-50` bypass in `reduce_pi_wide`: below exponent `CUT_PI_WIDE`
//! the absolute 2^-107 truncation is too coarse *relative* to `beta` itself
//! (there `m*beta < 1` never wraps, so the smallest true residual is `beta`
//! times a 24-bit integer, and chunk granularity dominates it), and those
//! exponents select `fc = |x|*(1/pi)` instead -- exact enough that the
//! residual is `x` itself to well under half an ulp.
//!
//! Generated, not hand-written: `(2^(e-150)/pi) mod 2` from a 900-bit
//! Machin-formula `pi` in exact integer arithmetic. See
//! `reduce_pi_wide` for the chain and the error budget it buys.

